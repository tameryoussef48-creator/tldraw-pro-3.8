export const DICTS: Record<LangCode, Dict> = { en, es, fr, de, pt, it, ar, zh, ja, ru };

export function isRtl(lang: LangCode): boolean {
  return RTL_LANGS.includes(lang);
}

export function getStoredLang(): LangCode {
  try {
    const v = localStorage.getItem(LANG_STORAGE_KEY) as LangCode | null;
    if (v && v in DICTS) return v;
  } catch {
    /* ignore */
  }
  return "en";
}

export function applyLangToDocument(lang: LangCode) {
  try {
    document.documentElement.lang = lang;
    document.documentElement.dir = isRtl(lang) ? "rtl" : "ltr";
    (window as unknown as Record<string, unknown>)["__hbiboI18n"] = { lang, dict: DICTS[lang] };
  } catch {
    /* ignore */
  }
}

function format(str: string, vars?: Record<string, string | number>): string {
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

type I18nContextValue = {
  lang: LangCode;
  setLang: (l: LangCode) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
};

export const I18nContext = createContext<I18nContextValue | null>(null);

export function useI18nProvider(): I18nContextValue {
  const [lang, setLangState] = useState<LangCode>(() => getStoredLang());

  useEffect(() => {
    applyLangToDocument(lang);
  }, [lang]);

  const setLang = useCallback((l: LangCode) => {
    setLangState(l);
    try {
      localStorage.setItem(LANG_STORAGE_KEY, l);
    } catch {
      /* ignore */
    }
  }, []);

  const t = useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      const dict = DICTS[lang] ?? DICTS.en;
      const raw = dict[key] ?? DICTS.en[key] ?? key;
      return format(raw, vars);
    },
    [lang],
  );

  return useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within an I18nContext.Provider");
  return ctx;
}
